-- 1. Criação da Tabela Principal de Cidadãos e Prontuários (PostgreSQL)
CREATE TABLE IF NOT EXISTS public.cidadaos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    cpf TEXT NOT NULL UNIQUE,
    dt_nascimento TEXT NOT NULL,
    matricula TEXT NOT NULL UNIQUE,
    mae TEXT NOT NULL,
    pai TEXT NOT NULL,
    origem TEXT NOT NULL CHECK (origem IN ('modulo', 'bpe')),
    link_processo_edocs TEXT NOT NULL DEFAULT 'https://treinamento.e-docs.es.gov.br/Processo/Protocolo/2026-D8TCS',
    criado_em TIMESTAMPTZ DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ DEFAULT NOW()
);

-- Índices para performance nas consultas
CREATE INDEX IF NOT EXISTS idx_supa_cidadaos_origem ON public.cidadaos(origem);
CREATE INDEX IF NOT EXISTS idx_supa_cidadaos_cpf ON public.cidadaos(cpf);
CREATE INDEX IF NOT EXISTS idx_supa_cidadaos_matricula ON public.cidadaos(matricula);

-- 2. Criação da Tabela de Auditoria de Operações de Escrita (Logs)
CREATE TABLE IF NOT EXISTS public.logs_operacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao TEXT NOT NULL CHECK (acao IN ('CADASTRO', 'ALTERACAO', 'EXCLUSAO')),
    cidadao_nome TEXT NOT NULL,
    cidadao_matricula TEXT NOT NULL,
    operador TEXT DEFAULT 'Operador',
    detalhes TEXT,
    data_hora TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Habilitar Row Level Security (RLS) e criar políticas de leitura/escrita para a aplicação
ALTER TABLE public.cidadaos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.logs_operacoes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura e escrita publica em cidadaos (PPI)" ON public.cidadaos;
CREATE POLICY "Permitir leitura e escrita publica em cidadaos (PPI)"
    ON public.cidadaos
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir leitura e escrita publica em logs_operacoes (PPI)" ON public.logs_operacoes;
CREATE POLICY "Permitir leitura e escrita publica em logs_operacoes (PPI)"
    ON public.logs_operacoes
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

